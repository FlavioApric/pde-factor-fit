exec(open(r'D:\ProblemaBase\research\R3\sympy\_hdr.py', encoding='utf8').read())
t, x, k = symbols('t x k', positive=True)
Lw = lambda u: diff(u, t) + diff(u, x, 3)
th = (3*t)**sp.Rational(1, 3)
check('Airy kernel (3t)^{-1/3} Ai(x/(3t)^{1/3})', Lw(airyai(x/th)/th), (t, x))
check('Bi profile (3t)^{-1/3} Bi(x/(3t)^{1/3})', Lw(airybi(x/th)/th), (t, x))
check('mode e^{ikx + i k^3 t}', Lw(exp(I*k*x + I*k**3*t)), (t, x, k))
check("Airy ODE y'' = x y (Ai)", diff(airyai(x), x, 2) - x*airyai(x), (x,))
check("Airy ODE y'' = x y (Bi)", diff(airybi(x), x, 2) - x*airybi(x), (x,))
check('dispersive polynomial x^3 - 6t', Lw(x**3 - 6*t), (t, x))
check('dispersive polynomial x^4 - 24 t x', Lw(x**4 - 24*t*x), (t, x))
S = exp(I*x**2/(4*t))/sqrt(4*pi*I*t)
check('free Schrodinger kernel (dt - i dxx)', diff(S, t) - I*diff(S, x, 2), (t, x))
