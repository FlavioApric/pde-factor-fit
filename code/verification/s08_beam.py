# R3 SymPy check s08 -- trave di Euler-Bernoulli dtt + dxxxx = (dt - i dxx)(dt + i dxx).
exec(open(r'D:\ProblemaBase\research\R3\sympy\_hdr.py', encoding='utf8').read())
t, x, k = symbols('t x k', positive=True); a, b = symbols('a b')
B = lambda u: diff(u, t, 2) + diff(u, x, 4)
Sp = lambda u: diff(u, t) - I*diff(u, x, 2)
Sm = lambda u: diff(u, t) + I*diff(u, x, 2)
f = Function('f')(t, x)
check('factorisation dtt+dxxxx = (dt - i dxx)(dt + i dxx)', B(f) - Sp(Sm(f)))
check('the two factors commute', Sp(Sm(f)) - Sm(Sp(f)))
Kp = exp(I*x**2/(4*t))/sqrt(4*pi*I*t)
Km = exp(-I*x**2/(4*t))/sqrt(-4*pi*I*t)
check('Kp in ker(dt - i dxx)', Sp(Kp), (t, x))
check('Km in ker(dt + i dxx)', Sm(Km), (t, x))
check('beam: Kp + Km in ker B', B(Kp + Km), (t, x))
check('beam mode cos(k^2 t) sin(kx)', B(cos(k**2*t)*sin(k*x)), (t, x, k))
check('a + b x in ker Sp', Sp(a + b*x)); check('a + b x in ker Sm', Sm(a + b*x))
for e in (cos(k*x), sin(k*x), cosh(k*x), sinh(k*x)):
    check(f'(dx^4 - k^4) {e}', diff(e, x, 4) - k**4*e, (x, k))
summary()
