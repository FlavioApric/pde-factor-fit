#!/usr/bin/env python3
"""Flatten a multi-file LaTeX document into ONE .tex file.

    python flatten_tex.py MAIN.tex OUT.tex [--bbl MAIN.bbl] [--drop REGEX ...] [--sub OLD=NEW ...]

* expands \\input{..}, \\include{..} and the project macro \\inc{..} recursively (paths relative to MAIN.tex's folder),
* replaces \\bibliography{..} (and a \\bibliographystyle{..} before it) by the contents of the .bbl (embedded thebibliography),
* removes \\externaldocument{..} lines, optional --drop patterns, applies --sub replacements.

Part of pde-factor-fit (c) 2026 Flavio Pricoco, MIT.
"""
import argparse
import os
import re
import sys

RX = re.compile(r"\\(?:input|include|inc)\{([^}]+)\}")


def resolve(base, name):
    cands = [name, name + ".tex"]
    for c in cands:
        p = os.path.normpath(os.path.join(base, c))
        if os.path.isfile(p):
            return p
    return None


def expand(path, base, seen):
    text = open(path, encoding="utf-8", errors="replace").read().replace("\r\n", "\n")
    out = []
    for line in text.split("\n"):
        stripped = line.lstrip()
        if stripped.startswith("%") or "\\newcommand{\\inc}" in line or "\\def\\inc" in line:
            out.append(line)
            continue
        pos = 0
        piece = ""
        for m in RX.finditer(line):
            # skip occurrences after an unescaped comment sign
            if "%" in line[: m.start()].replace("\\%", ""):
                break
            p = resolve(base, m.group(1).strip())
            piece += line[pos : m.start()]
            if p is None:
                piece += m.group(0)  # keep (e.g. a package or optional file)
            else:
                if p in seen:
                    raise SystemExit(f"cyclic input: {p}")
                piece += "\n% ---- begin " + os.path.relpath(p, base) + "\n" + expand(p, base, seen | {p}) + "\n% ---- end " + os.path.relpath(p, base) + "\n"
            pos = m.end()
        piece += line[pos:]
        out.append(piece)
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("main")
    ap.add_argument("out")
    ap.add_argument("--bbl")
    ap.add_argument("--drop", action="append", default=[])
    ap.add_argument("--sub", action="append", default=[])
    a = ap.parse_args()
    base = os.path.dirname(os.path.abspath(a.main))
    s = expand(os.path.abspath(a.main), base, {os.path.abspath(a.main)})
    s = re.sub(r"^\s*\\externaldocument(\[[^\]]*\])?\{[^}]*\}\s*$", "", s, flags=re.M)
    for pat in a.drop:
        s = re.sub(pat, "", s, flags=re.M)
    if a.bbl:
        bbl = open(a.bbl, encoding="utf-8", errors="replace").read()
        s = re.sub(r"(?:\\IfFileExists\{[^}]*\.bst\}\{\\bibliographystyle\{[^}]*\}\}\{\\bibliographystyle\{[^}]*\}\}\s*)?(?:\\bibliographystyle\{[^}]*\}\s*)?\\bibliography\{[^}]*\}",
                   lambda m: "% embedded bibliography (generated by BibTeX from the .bib files of the earlier multi-file version)\n" + bbl, s)
    for sub in a.sub:
        old, new = sub.split("=>", 1)
        s = s.replace(old, new)
    open(a.out, "w", encoding="utf-8").write(s)
    print(f"{a.out}: {len(s)} bytes, {s.count(chr(10))} lines")


if __name__ == "__main__":
    main()
